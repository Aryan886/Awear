export function number(value: number, decimals = 0) {
  return new Intl.NumberFormat('en-IN', {
    maximumFractionDigits: decimals,
    minimumFractionDigits: decimals,
    numberingSystem: 'latn',
  }).format(Number.isFinite(value) ? value : 0);
}
export function time(timeMs: number, language = i18n.language) {
  return new Intl.DateTimeFormat(`${language}-IN`, {
    hour: 'numeric',
    minute: '2-digit',
    numberingSystem: 'latn',
  }).format(timeMs);
}
export function duration(seconds: number) {
  const wholeSeconds = Math.max(0, Math.floor(seconds));
  return `${Math.floor(wholeSeconds / 60)
    .toString()
    .padStart(2, '0')}:${(wholeSeconds % 60).toString().padStart(2, '0')}`;
}
